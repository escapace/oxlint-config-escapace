import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, rmSync } from 'node:fs'
import path from 'node:path'
import { format } from 'oxfmt'
import formatterConfiguration from '../../oxfmt.config.ts'
import { rootDirectory } from './paths.ts'

export interface EmittedFile {
  content: string
  path: string
}

const header = (origin: string): string =>
  `// Generated by scripts/codegen.ts from ${origin}. Do not edit; run \`pnpm run codegen\`.\n`

const { ignorePatterns: _ignorePatterns, ...formatOptions } = formatterConfiguration

/** Formats with oxfmt and the repository's own settings (the API reads no config file). */
const formatText = async (relativePath: string, text: string): Promise<string> => {
  const result = await format(relativePath, text, formatOptions)

  if (result.errors.length > 0) {
    throw new Error(
      `oxfmt could not format ${relativePath}: ${result.errors.map((error) => error.message).join('; ')}`,
    )
  }

  return result.code
}

/**
 * Formats with oxfmt; `fix`, when given, runs on the formatted text and the
 * result is formatted again until stable, because sort rules compare node text
 * and therefore depend on the final layout.
 */
export const emitTypescript = async (
  relativePath: string,
  body: string,
  origin: string,
  fix?: (code: string, filename: string) => string,
): Promise<EmittedFile> => {
  const prettify = async (code: string): Promise<string> => await formatText(relativePath, code)
  let content = await prettify(header(origin) + body)

  if (fix === undefined) {
    return { content, path: relativePath }
  }

  for (let pass = 0; pass < 3; pass += 1) {
    const next = await prettify(fix(content, relativePath))

    if (next === content) {
      break
    }

    content = next
  }

  return { content, path: relativePath }
}

export const emitJson = (relativePath: string, value: unknown): EmittedFile => ({
  content: `${JSON.stringify(value, null, 2)}\n`,
  path: relativePath,
})

export const writeFiles = (files: EmittedFile[], managedDirectories: string[]): void => {
  for (const directory of managedDirectories) {
    const absolute = path.join(rootDirectory, directory)

    if (existsSync(absolute)) {
      for (const entry of readdirSync(absolute)) {
        rmSync(path.join(absolute, entry), { force: true, recursive: true })
      }
    }
  }

  for (const file of files) {
    const absolute = path.join(rootDirectory, file.path)
    mkdirSync(path.dirname(absolute), { recursive: true })
    writeFileSync(absolute, file.content)
  }
}

export const checkFiles = (files: EmittedFile[], managedDirectories: string[]): string[] => {
  const problems: string[] = []
  const expected = new Set(files.map((file) => file.path))

  for (const file of files) {
    const absolute = path.join(rootDirectory, file.path)

    if (!existsSync(absolute)) {
      problems.push(`missing: ${file.path}`)
    } else if (readFileSync(absolute, 'utf8') !== file.content) {
      problems.push(`stale: ${file.path}`)
    }
  }

  for (const directory of managedDirectories) {
    const absolute = path.join(rootDirectory, directory)

    if (!existsSync(absolute)) {
      continue
    }

    const walk = (current: string): void => {
      for (const entry of readdirSync(current, { withFileTypes: true })) {
        const full = path.join(current, entry.name)

        if (entry.isDirectory()) {
          walk(full)
        } else if (!expected.has(path.relative(rootDirectory, full))) {
          problems.push(`unexpected: ${path.relative(rootDirectory, full)}`)
        }
      }
    }

    walk(absolute)
  }

  return problems
}
